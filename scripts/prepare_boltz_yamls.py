"""Generate Boltz-2 input YAMLs for WT/PLM3/PLM5/en31 + sgRNA + DNA.

sgRNA + DNA sequences are extracted from 5B2O (with 2'-deoxyuridine
substitutions in the synthetic sgRNA tail mapped back to U). Protein
sequences come from the WT FASTA plus the candidate builders.

Writes one YAML per variant to hpc/inputs/ which the sbatch will
iterate over.
"""
from __future__ import annotations

import argparse
import logging
import sys
from collections import defaultdict
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(message)s")
log = logging.getLogger(__name__)

from nuclease_design.io import load_fasta
from nuclease_design.variants import apply_mutant, parse_mutant


PROT_3TO1 = {
    "ALA":"A","ARG":"R","ASN":"N","ASP":"D","CYS":"C","GLN":"Q","GLU":"E",
    "GLY":"G","HIS":"H","ILE":"I","LEU":"L","LYS":"K","MET":"M","PHE":"F",
    "PRO":"P","SER":"S","THR":"T","TRP":"W","TYR":"Y","VAL":"V",
}
RNA_3TO1 = {"A":"A","U":"U","G":"G","C":"C","DU":"U"}
DNA_3TO1 = {"DA":"A","DT":"T","DG":"G","DC":"C"}


def extract_chain(pdb_path: Path, chain_id: str, kind: str) -> str:
    table = {"protein": PROT_3TO1, "rna": RNA_3TO1, "dna": DNA_3TO1}[kind]
    backbone_atom = {"protein": "CA", "rna": "C1'", "dna": "C1'"}[kind]
    residues: list[tuple[int, str]] = []
    seen: set[int] = set()
    for line in pdb_path.read_text().splitlines():
        if not line.startswith("ATOM"):
            continue
        if line[21] != chain_id:
            continue
        atom = line[12:16].strip()
        if atom != backbone_atom:
            continue
        resseq = int(line[22:26])
        if resseq in seen:
            continue
        seen.add(resseq)
        residues.append((resseq, line[17:20].strip()))
    residues.sort()
    seq = "".join(table.get(r, "?") for _, r in residues)
    if "?" in seq:
        raise ValueError(f"Unknown residue codes in chain {chain_id}: "
                         f"{[r for _, r in residues if r not in table]}")
    return seq


def write_yaml(out_path: Path, name: str, protein_seq: str,
               rna_seq: str, dna_c_seq: str, dna_d_seq: str,
               use_msa_server: bool = True) -> None:
    """Boltz-2 YAML schema (v1).

    If use_msa_server is True (default), omit any `msa:` field so the runtime
    `--use_msa_server` flag can fetch a ColabFold MSA — produces meaningfully
    better predictions for the 1,629-aa FnCas9 protein.

    If False, set `msa: empty` to force single-sequence inference (faster but
    lower-confidence). Use only when MSA fetch is unavailable / undesired.
    """
    msa_line = "" if use_msa_server else "\n      msa: empty"
    content = f"""# Boltz-2 input for {name}
# Generated by scripts/prepare_boltz_yamls.py
version: 1
sequences:
  - protein:
      id: A
      sequence: {protein_seq}{msa_line}
  - rna:
      id: B
      sequence: {rna_seq}
  - dna:
      id: C
      sequence: {dna_c_seq}
  - dna:
      id: D
      sequence: {dna_d_seq}
"""
    out_path.write_text(content)
    log.info("Wrote %s  (protein %d aa%s)", out_path, len(protein_seq),
             ", single-sequence mode" if not use_msa_server else "")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--pdb", default="data/raw/5B2O.pdb")
    parser.add_argument("--wt-fasta", default="data/raw/A0Q5Y3_fncas9.fasta")
    parser.add_argument("--output-dir", default="hpc/inputs")
    parser.add_argument("--single-sequence", action="store_true",
                        help="Force msa: empty (faster, lower-confidence). "
                             "Default is to omit msa: line so --use_msa_server can fetch ColabFold MSA.")
    parser.add_argument("--truncate",
                        help="Truncate protein to a UniProt residue range, e.g. '1230-1620' for WED+PI only. "
                             "Mutations applied first, then truncation. Use this to fit on smaller GPUs "
                             "(V100 32GB OOMs on full 1629-aa FnCas9 with sgRNA+DNA).")
    args = parser.parse_args()

    pdb_path = Path(args.pdb)
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    log.info("Extracting nucleic-acid chains from %s ...", pdb_path)
    sgRNA = extract_chain(pdb_path, "B", "rna")
    dna_C = extract_chain(pdb_path, "C", "dna")
    dna_D = extract_chain(pdb_path, "D", "dna")
    log.info("  sgRNA (chain B, %d nt): %s", len(sgRNA), sgRNA)
    log.info("  DNA   (chain C, %d nt): %s", len(dna_C), dna_C)
    log.info("  DNA   (chain D, %d nt): %s", len(dna_D), dna_D)

    wt = load_fasta(Path(args.wt_fasta))[0].sequence
    log.info("\nFnCas9 WT: %d aa", len(wt))

    variants = {
        "fncas9_wt":    ("FnCas9-WT",   wt),
        "fncas9_plm3":  ("FnCas9-PLM3", apply_mutant(wt, parse_mutant("G1243T/W1507K/C1292K/M1617K"))),
        "fncas9_plm4":  ("FnCas9-PLM4", apply_mutant(wt, parse_mutant("T1535V/Y1249F/Y1341L/A1325K"))),
        "fncas9_plm5":  ("FnCas9-PLM5", apply_mutant(wt, parse_mutant("Y1249F/Y1341L/A1325K/K1479F"))),
        "fncas9_en31":  ("FnCas9-en31", apply_mutant(wt, parse_mutant("G1243T/E1369R/E1449H"))),
    }

    if args.truncate:
        lo, hi = (int(x) for x in args.truncate.split("-"))
        log.info("\nTruncating protein chains to UniProt residues %d-%d (length %d)",
                 lo, hi, hi - lo + 1)
        variants = {slug: (name, seq[lo - 1:hi]) for slug, (name, seq) in variants.items()}

    use_msa = not args.single_sequence
    for slug, (name, seq) in variants.items():
        yaml_path = out_dir / f"boltz_{slug}.yaml"
        write_yaml(yaml_path, name, seq, sgRNA, dna_C, dna_D, use_msa_server=use_msa)

    log.info("\nDone. %d YAMLs in %s/", len(variants), out_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
